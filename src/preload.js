const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("execej", {
  version: () => ipcRenderer.invoke("app:version"),
  loadConfig: () => ipcRenderer.invoke("config:load"),
  saveConfig: (config) => ipcRenderer.invoke("config:save", config),
  listProtocols: () => ipcRenderer.invoke("protocols:list"),
  saveProtocol: (protocol) => ipcRenderer.invoke("protocols:save", protocol),
  deleteProtocol: (id) => ipcRenderer.invoke("protocols:delete", id),
  inspectProtocolOds: (odsPath) => ipcRenderer.invoke("protocols:inspectOds", odsPath),
  listProtocolFiles: (folderPath) => ipcRenderer.invoke("protocols:listFiles", folderPath),
  pickFile: (options) => ipcRenderer.invoke("dialog:file", { kind: "file", ...options }),
  pickFolder: (options) => ipcRenderer.invoke("dialog:file", { kind: "folder", ...options }),
  pickFiles: (options) => ipcRenderer.invoke("dialog:files", options),
  openPath: (target) => ipcRenderer.invoke("shell:openPath", target),
  listSheets: (odsPath) => ipcRenderer.invoke("ods:sheets", odsPath),
  loadNames: (payload) => ipcRenderer.invoke("merge:names", payload),
  createInitialFolder: (payload) => ipcRenderer.invoke("initial:create", payload),
  analyzeMovements: (payload) => ipcRenderer.invoke("movements:analyze", payload),
  movementAttachmentRequirements: (payload) => ipcRenderer.invoke("movements:attachmentRequirements", payload),
  listOnrCertificates: () => ipcRenderer.invoke("onr:certificates:list"),
  createAutuationPreview: (protocolId) => ipcRenderer.invoke("movements:autuationPreview", protocolId),
  closeAutuationPreview: (previewId) => ipcRenderer.invoke("movements:autuationPreview:close", previewId),
  autuarMovimentacao: (payload) => ipcRenderer.invoke("movements:autuar", payload),
  estornarAutuacao: (payload) => ipcRenderer.invoke("movements:estornarAutuacao", payload),
  generateFinalPdf: (payload) => ipcRenderer.invoke("finalPdf:generate", payload),
  onFinalPdfProgress: (callback) => ipcRenderer.on("finalPdf:progress", (_event, message) => callback(message)),
  convertToPdfA: (payload) => ipcRenderer.invoke("pdfa:convert", payload),
  onPdfAProgress: (callback) => ipcRenderer.on("pdfa:progress", (_event, message) => callback(message)),
  generateArispStats: (payload) => ipcRenderer.invoke("arisp:generate", payload),
  onArispStatsProgress: (callback) => ipcRenderer.on("arisp:progress", (_event, message) => callback(message)),
  onOnrSigningProgress: (callback) => ipcRenderer.on("onr:signingProgress", (_event, message) => callback(message)),
  notePreview: (payload) => ipcRenderer.invoke("note:preview", payload),
  generateNote: (payload) => ipcRenderer.invoke("note:generate", payload),
  generateDocuments: (payload) => ipcRenderer.invoke("documents:generate", payload),
  checkUpdates: () => ipcRenderer.invoke("update:check"),
  downloadUpdate: () => ipcRenderer.invoke("update:download"),
  installUpdate: () => ipcRenderer.invoke("update:install"),
  onUpdateAvailable: (callback) => ipcRenderer.on("update:available", (_event, data) => callback(data)),
  onUpdateNotAvailable: (callback) => ipcRenderer.on("update:notAvailable", callback),
  onUpdateProgress: (callback) => ipcRenderer.on("update:progress", (_event, data) => callback(data)),
  onUpdateDownloaded: (callback) => ipcRenderer.on("update:downloaded", callback)
});
